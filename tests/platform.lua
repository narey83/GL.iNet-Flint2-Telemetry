local platform = require("flint2.platform")
local path = os.tmpname()
local function command(value) assert(os.execute(value) == 0) end
local function quoted(value) return "'" .. value:gsub("'", "'\\''") .. "'" end
local file = assert(io.open(path, "w")); file:write("test-only\n"); file:close()
command("chmod 600 " .. quoted(path))
assert(platform.private_file(path), "owner-only file rejected")
command("chmod 640 " .. quoted(path))
assert(not platform.private_file(path), "group-readable file accepted")
command("chmod 604 " .. quoted(path))
assert(not platform.private_file(path), "other-readable file accepted")
command("chmod 600 " .. quoted(path))
command("ln -s " .. quoted(path) .. " " .. quoted(path .. ".link"))
assert(not platform.private_file(path .. ".link"), "symlink accepted")
assert(not platform.private_file("/tmp"), "directory accepted")
os.remove(path .. ".link"); os.remove(path)
assert(not platform.private_file(path), "missing file accepted")
platform.reset_sigterm()
print("PASS: platform file permissions, symlinks, type and signal reset")
